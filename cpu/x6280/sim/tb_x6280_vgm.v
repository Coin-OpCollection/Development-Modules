//============================================================================
//  Agnostic VGM playback testbench for the HuC6280 PSG implementation.
//
//  Reads a combined playlist hex file (generated by vgm2hex.py) containing
//  any number of tracks with per-track clock configuration. Outputs
//  sequentially numbered raw 24-bit signed stereo PCM files that
//  wav_batch.py converts to named 16-bit stereo WAV files using the
//  tracklist index.
//
//  Playlist format (32-bit hex words loaded via $readmemh):
//    3_CC_CC_CC  = Track start (lower 24 bits = CEN ticks per sample)
//    1_00_RR_DD  = Write data DD to PSG register RR ($1FE800 + RR)
//    2_WW_WW_WW  = Wait WWWWWW samples (at 44100 Hz)
//    0_00_00_00  = End of track
//    F_00_00_00  = End of playlist
//
//  Sample stream format (per output sample, 6 bytes little-endian):
//    [ldata[7:0], ldata[15:8], ldata[23:16], rdata[7:0], rdata[15:8], rdata[23:16]]
//
//  Usage:
//    python scripts/vgm2hex.py
//    vlog tb_x6280_vgm.v ../hdl/x6280_psg.v
//    vsim -c tb_x6280_vgm -do "run -all; quit -f"
//    python scripts/wav_batch.py
//
//  Reference: HuC6280 CMOS 8-bit Microprocessor PSG Manual
//             VGM file format specification (HuC6280 PSG = command 0xB9,
//             clock at header offset 0xA4)
//============================================================================
`timescale 1ns/1ps

module tb_x6280_vgm;

//=========================================================================
// Configuration
//=========================================================================
localparam MAX_CMDS = 4194304;

//=========================================================================
// Test Signals
//=========================================================================
reg               clk;
reg               rst_n;
reg               clken;
reg               we;
reg        [3:0]  a;
reg        [7:0]  di;
wire signed [23:0] ldata;
wire signed [23:0] rdata;

//=========================================================================
// DUT Instantiation
//=========================================================================
x6280_psg uut (
    .clk       ( clk       ),
    .rst_n     ( rst_n     ),
    .clken     ( clken     ),
    .we        ( we        ),
    .a         ( a         ),
    .di        ( di        ),
    .dac_latch ( 1'b1      ),
    .ldata     ( ldata     ),
    .rdata     ( rdata     )
);

//=========================================================================
// Clock Generation
//=========================================================================
initial clk = 0;
always #5 clk = ~clk;

//=========================================================================
// Helper Tasks
//=========================================================================
task cycle;
    begin
        @(posedge clk);
        #1 clken = 1;
        @(posedge clk);
        #1 clken = 0;
    end
endtask

task write_reg;
    input [3:0] reg_addr;
    input [7:0] data_byte;
    begin
        @(posedge clk);
        #1;
        a     = reg_addr;
        di    = data_byte;
        we    = 1'b1;
        clken = 1'b1;
        @(posedge clk);
        #1;
        we    = 1'b0;
        clken = 1'b0;
    end
endtask

task reset_system;
    begin
        rst_n = 0;
        clken = 0;
        we    = 0;
        a     = 4'h0;
        di    = 8'h00;
        #100;
        rst_n = 1;
        #50;
        cycle();
    end
endtask

//=========================================================================
// Sample Capture (24-bit signed -> 6 bytes little-endian per sample)
//=========================================================================
task write_sample;
    input integer fd_in;
    begin
        $fwrite(fd_in, "%c%c%c%c%c%c",
                ldata[ 7: 0],
                ldata[15: 8],
                ldata[23:16],
                rdata[ 7: 0],
                rdata[15: 8],
                rdata[23:16]);
    end
endtask

//=========================================================================
// Playlist Memory and Playback
//=========================================================================
reg [31:0] playlist [0:MAX_CMDS-1];

integer fd;
integer cmd_idx;
integer track_num;
integer total_samples;
integer cen_per_sample;
integer wait_samples;
integer cen_count;
integer s;
integer done;
integer track_active;

reg [3:0]   cmd_type;
reg [1023:0] raw_filename;

initial begin
    $display("=============================================================");
    $display("  HuC6280 PSG VGM Playlist Testbench");
    $display("=============================================================\n");

    $readmemh("output/vgm_hex/playlist.hex", playlist);

    cmd_idx   = 0;
    track_num = 0;
    done      = 0;
    fd        = 0;

    while(!done && cmd_idx < MAX_CMDS) begin
        cmd_type = playlist[cmd_idx][31:28];

        case(cmd_type)
            // End of playlist
            4'hF: begin
                done = 1;
            end

            // Track start marker
            4'h3: begin
                track_num = track_num + 1;
                cen_per_sample = playlist[cmd_idx][27:0];
                $display("  [Track %0d] CEN/sample=%0d", track_num, cen_per_sample);

                $sformat(raw_filename, "output/wav/track_%02d.raw", track_num);
                fd = $fopen(raw_filename, "wb");

                if(fd == 0) begin
                    $display("    ERROR: Could not open output file");
                    while(cmd_idx < MAX_CMDS && playlist[cmd_idx][31:28] != 4'h0)
                        cmd_idx = cmd_idx + 1;
                end else begin
                    reset_system();
                    total_samples = 0;
                    track_active  = 1;

                    while(track_active && cmd_idx < MAX_CMDS - 1) begin
                        cmd_idx  = cmd_idx + 1;
                        cmd_type = playlist[cmd_idx][31:28];

                        case(cmd_type)
                            // End of track - silence all 6 channels then drain
                            4'h0: begin
                                for(s = 0; s < 6; s = s + 1) begin
                                    write_reg(4'h0, s[7:0]);   // R0 select channel
                                    write_reg(4'h4, 8'h00);    // R4 ChON=0, AL=0
                                end
                                for(s = 0; s < 256; s = s + 1) begin
                                    for(cen_count = 0; cen_count < cen_per_sample; cen_count = cen_count + 1)
                                        cycle();
                                    write_sample(fd);
                                    total_samples = total_samples + 1;
                                end

                                $fclose(fd);
                                fd = 0;
                                $display("    -> %0d samples (%0d.%0d sec)",
                                         total_samples, total_samples / 44100,
                                         (total_samples % 44100) * 10 / 44100);
                                track_active = 0;
                            end

                            // Register write: lower 16 bits = {RR, DD}
                            4'h1: begin
                                write_reg(playlist[cmd_idx][11:8], playlist[cmd_idx][7:0]);
                            end

                            // Wait
                            4'h2: begin
                                wait_samples = playlist[cmd_idx][27:0];
                                for(s = 0; s < wait_samples; s = s + 1) begin
                                    for(cen_count = 0; cen_count < cen_per_sample; cen_count = cen_count + 1)
                                        cycle();
                                    write_sample(fd);
                                    total_samples = total_samples + 1;
                                end
                            end

                            default: ;
                        endcase
                    end
                end
            end

            default: ;
        endcase

        cmd_idx = cmd_idx + 1;
    end

    $display("\n=============================================================");
    $display("  Playlist complete: %0d tracks", track_num);
    $display("  Run: python scripts/wav_batch.py");
    $display("=============================================================\n");

    $stop;
end

endmodule
